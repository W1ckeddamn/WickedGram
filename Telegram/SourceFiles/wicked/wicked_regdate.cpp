int64 RegDate::EstimateTimestamp(uint64 userId) {
	if (userId == 0 || kRegTable.empty()) {
		return 0;
	}

	if (userId <= kRegTable.front().id) {
		return kRegTable.front().date;
	}
	if (userId >= kRegTable.back().id) {
		return kRegTable.back().date;
	}

	const auto it = std::lower_bound(
		kRegTable.begin(),
		kRegTable.end(),
		userId,
		[](const RegPoint &p, uint64 id) {
			return p.id < id;
		});

	if (it == kRegTable.end()) {
		return kRegTable.back().date;
	}
	if (it->id == userId) {
		return it->date;
	}

	const auto prev = it - 1;
	const auto id0 = prev->id;
	const auto id1 = it->id;
	const auto t0 = prev->date;
	const auto t1 = it->date;

	if (id1 > id0) {
		const auto fraction = double(userId - id0) / double(id1 - id0);
		return int64(double(t0) + double(t1 - t0) * fraction);
	}
	return t0;
}

QString RegDate::FormatRegistrationDate(uint64 userId) {
	const auto ts = EstimateTimestamp(userId);
	if (ts <= 0) {
		return QString();
	}

	const auto dt = QDateTime::fromSecsSinceEpoch(ts);
	const auto monthName = QLocale().standaloneMonthName(dt.date().month(), QLocale::LongFormat);
	return QString(u"~%1 %2"_q)
		.arg(monthName)
		.arg(dt.date().year());
}

